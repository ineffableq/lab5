// Завдання 3 (№149): Перевірити, чи всі члени другої послідовності входять до першої[cite: 30]
// -------------------------------------------------------------------
void task3() {
    printf("\n--- Завдання №149 ---\n");
    int n, m;

    printf("Введіть розмір першого масиву A (n): ");
    scanf("%d", &n);
    int a[100];
    printf("Введіть %d елементів масиву A:\n", n);
    for (int i = 0; i < n; i++) {
        scanf("%d", &a[i]);
    }

    printf("Введіть розмір другого масиву B (m, де m < n): ");
    scanf("%d", &m);
    int b[100];
    printf("Введіть %d елементів масиву B:\n", m);
    for (int i = 0; i < m; i++) {
        scanf("%d", &b[i]);
    }

    int all_included = 1;

    for (int i = 0; i < m; i++) {
        int found_in_A = 0;
        for (int j = 0; j < n; j++) {
            if (b[i] == a[j]) {
                found_in_A = 1;
                break;
            }
        }
        if (!found_in_A) {
            all_included = 0;
            break;
        }
    }

    if (all_included) {
        printf("\nТак, всі члени масиву B входять до масиву A.\n");
    } else {
        printf("\nНі, не всі члени масиву B входять до масиву A.\n");
    }
}

