// Завдання 1 (№123): Знайти добуток елементів масиву, більших за M[cite: 29]
// -------------------------------------------------------------------
void task1() {
    printf("\n--- Завдання №123 ---\n");
    int n;
    long long M;

    printf("Введіть розмір масиву n: ");
    scanf("%d", &n);

    long long a[100];
    printf("Введіть %d цілих додатних елементів масиву:\n", n);
    for (int i = 0; i < n; i++) {
        scanf("%lld", &a[i]);
    }

    printf("Введіть число M: ");
    scanf("%lld", &M);

    long long product = 1;
    int found = 0;

    for (int i = 0; i < n; i++) {
        if (a[i] > M) {
            product *= a[i];
            found = 1;
        }
    }

    if (found) {
        printf("Добуток елементів, більших за %lld: %lld\n", M, product);
    } else {
        printf("Елементів, більших за %lld, у масиві немає.\n", M);
    }
}

