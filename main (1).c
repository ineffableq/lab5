// Завдання 2 (№130): Знайти елементи, що є квадратами числа m[cite: 29]
// -------------------------------------------------------------------
void task2() {
    printf("\n--- Завдання №130 ---\n");
    int n;

    printf("Введіть розмір масиву n: ");
    scanf("%d", &n);

    int a[100];
    printf("Введіть %d цілих додатних елементів:\n", n);
    for (int i = 0; i < n; i++) {
        scanf("%d", &a[i]);
    }

    int found = 0;
    printf("\nЕлементи, що є точними квадратами деяких чисел:\n");
    for (int i = 0; i < n; i++) {
        for (int m = 1; m * m <= a[i]; m++) {
            if (m * m == a[i]) {
                printf("a[%d] = %d (це %d^2)\n", i, a[i], m);
                found = 1;
                break;
            }
        }
    }

    if (!found) {
        printf("Елементів, що є квадратами цілих чисел, не знайдено.\n");
    }
}

