// Завдання 6 (№128): Знайти перший максимальний елемент і замінити його 0[cite: 29]
// -------------------------------------------------------------------
void task6() {
    printf("\n--- Завдання №128 ---\n");
    int n;

    printf("Введіть розмір масиву n: ");
    scanf("%d", &n);

    double a[100];
    printf("Введіть %d дійсних елементів масиву:\n", n);
    for (int i = 0; i < n; i++) {
        scanf("%lf", &a[i]);
    }

    // Знаходимо перший максимальний елемент
    int max_idx = 0;
    for (int i = 1; i < n; i++) {
        if (a[i] > a[max_idx]) {
            max_idx = i;
        }
    }

    printf("\nПерший максимум знайдено на позиції a[%d] зі значенням %.2f\n", max_idx, a[max_idx]);
    a[max_idx] = 0.0; // Заміна першого максимального нулем

    printf("Масив після заміни першого максимуму нулем:\n");
    for (int i = 0; i < n; i++) {
        printf("%.2f ", a[i]);
    }
    printf("\n");
}