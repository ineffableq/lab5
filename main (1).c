// Завдання 4 (№186): Перемістити від'ємні елементи на початок без додаткового масиву[cite: 34]
// -------------------------------------------------------------------
void task4() {
    printf("\n--- Завдання №186 ---\n");
    int n;

    printf("Введіть розмір масиву n: ");
    scanf("%d", &n);

    double a[100];
    printf("Введіть %d елементів масиву:\n", n);
    for (int i = 0; i < n; i++) {
        scanf("%lf", &a[i]);
    }

    // Алгоритм вставки (Insertion Style) для збереження порядку прямування без додаткового масиву
    for (int i = 0; i < n; i++) {
        if (a[i] < 0) {
            double temp = a[i];
            int j = i;
            // Зсуваємо невід'ємні елементи праворуч
            while (j > 0 && a[j - 1] >= 0) {
                a[j] = a[j - 1];
                j--;
            }
            a[j] = temp;
        }
    }

    printf("\nМодифікований масив (від'ємні попереду зі збереженням порядку):\n");
    for (int i = 0; i < n; i++) {
        printf("%.2f ", a[i]);
    }
    printf("\n");
}

