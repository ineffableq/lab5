// Завдання 5 (№37): Знайти елементи, у яких остача від ділення на M дорівнює L[cite: 25]
// -------------------------------------------------------------------
void task5() {
    printf("\n--- Завдання №37 ---\n");
    int n, M, L;

    printf("Введіть розмір масиву n: ");
    scanf("%d", &n);

    int a[100];
    printf("Введіть %d натуральних елементів масиву:\n", n);
    for (int i = 0; i < n; i++) {
        scanf("%d", &a[i]);
    }

    printf("Введіть число M (знаменник ділення): ");
    scanf("%d", &M);
    printf("Введіть число L (бажана остача, 0 <= L < M): ");
    scanf("%d", &L);

    printf("\nЕлементи, чия остача від ділення на %d дорівнює %d:\n", M, L);
    int found = 0;
    for (int i = 0; i < n; i++) {
        if (a[i] % M == L) {
            printf("a[%d] = %d\n", i, a[i]);
            found = 1;
        }
    }

    if (!found) {
        printf("Таких елементів у масиві немає.\n");
    }
}

